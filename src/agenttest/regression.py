class RegressionManifest(StrictModel):
    schema_version: str = Field(pattern=r"^agenttest\.regression\.v1$")
    source_run_id: str = Field(pattern=r"^[a-f0-9]{32}$")
    source_report_sha256: str = Field(pattern=r"^[a-f0-9]{64}$")
    scenario_sha256: str = Field(pattern=r"^[a-f0-9]{64}$")
    contract_sha256: str = Field(pattern=r"^[a-f0-9]{64}$")
    target_config_sha256: str = Field(pattern=r"^[a-f0-9]{64}$")
    policy_sha256: str = Field(pattern=r"^[a-f0-9]{64}$")
    task_contract_sha256: str = Field(pattern=r"^[a-f0-9]{64}$")
    step_policy_sha256: dict[str, str]
    source_step_policy_sha256: dict[str, str]
    test_module: str = Field(pattern=r"^test_agenttest_[a-f0-9]{32}\.py$")
    files: dict[str, str]


@dataclass(repr=False)
class RegressionRuntime:
    """Selected by the operator, never loaded from an exported plan or model reply."""

    contract_document: bytes
    target: TargetConfig
    registry: PolicyRegistry
    task_contract: TaskContract
    environ: dict[str, str]
    transport: httpx.AsyncBaseTransport | None
    store: ReportStore


class RegressionCapture:
    """Keep a candidate DSL in memory only; export still requires full successful evidence."""

    def __init__(self, delegate):
        self.delegate, self.scenario = delegate, None

    @property
    def stats(self) -> ModelCallStats | None:
        return getattr(self.delegate, "stats", None)

    async def generate(self, context: dict) -> str:
        self.scenario = None
        raw = await self.delegate.generate(context)
        try:
            self.scenario = Scenario.model_validate(bounded_json(raw, 100_000))
        except (ValueError, TypeError, RecursionError):
            pass
        return raw


def validate_destination(output: Path) -> Path:
    path = output.absolute()
    if ".." in output.parts or not re.fullmatch(r"[A-Za-z][A-Za-z0-9_-]{0,60}", path.name):
        raise ValueError("REGRESSION_OUTPUT_INVALID")
    with pinned_directory(path.parent, "", create=False):
        if os.path.lexists(path):
            raise ValueError("REGRESSION_OUTPUT_EXISTS")
    return path


def _validated(runtime: RegressionRuntime, scenario: Scenario):
    target = TargetConfig.model_validate(runtime.target.model_dump())
    task = TaskContract.model_validate_json(runtime.task_contract.model_dump_json())
    contract = load_openapi(bytes(runtime.contract_document))
    registry = runtime.registry.snapshot()
    task_validator(task, contract, target, registry)(task.user_task, scenario)
    vault = CredentialVault(target, runtime.environ)
    raw = json.dumps(scenario.model_dump(), ensure_ascii=False)
    contains_secret = vault.contains_secret(scenario.model_dump()) or any(
        value and value in raw for name, value in runtime.environ.items() if sensitive_field(name))
    vault.close()
    if contains_secret or PRIVATE_LITERAL.search(raw):
        raise ValueError("REGRESSION_SENSITIVE_DATA")
    for step in scenario.steps:
        if step.upload or step.poll or step.read_retries:
            raise ValueError("REGRESSION_JSON_SCOPE_REQUIRED")
        def sensitive(value):
            if isinstance(value, dict):
                return any(sensitive_field(str(k), target.sensitive_fields) or sensitive(v)
                           for k, v in value.items())
            return isinstance(value, list) and any(sensitive(v) for v in value)

        if any(sensitive_field(key, target.sensitive_fields) or sensitive(binding.value)
               for location in (step.body, step.query, step.path_parameters)
               for key, binding in location.items()):
            raise ValueError("REGRESSION_SENSITIVE_DATA")
    executor = Executor(target, contract, runtime.store, runtime.transport,
                        dict(runtime.environ), registry)
    _, policies = executor.validate(scenario)
    identity = {"scenario_sha256": fingerprint(scenario.model_dump()),
                "contract_sha256": fingerprint(contract.model_dump()),
                "target_config_sha256": fingerprint(target.model_dump()),
                "policy_sha256": registry.digest(),
                "task_contract_sha256": fingerprint(task.model_dump(mode="json")),
                "step_policy_sha256": {key: fingerprint(p.model_dump())
                                       for key, p in policies.items()}}
    return executor, identity


def export_regression(output: Path, runtime: RegressionRuntime, scenario: Scenario,
                      source: RunReport) -> RegressionManifest:
    """Export data only after exact plan, policy, intent and complete execution checks."""
    scenario = Scenario.model_validate_json(scenario.model_dump_json())
    executor, identity = _validated(runtime, scenario)
    proof = capture_plan(scenario)
    structure = [{key: getattr(step, key) for key in (
        "step_id", "operation_id", "role", "policy_id", "argument_sha256", "dependencies")}
        for step in proof.steps]
    if not (source.outcome == Outcome.PASS and source.completed and source.workflow_completed
            and source.task_mode == "natural_language" and source.task_satisfied is True
            and source.plan_valid and source.dsl_valid and source.policy_authorized
            and source.intent_verified and source.scenario_sha256 == identity["scenario_sha256"]
            and source.contract_sha256 == identity["contract_sha256"]
            and source.target_config_sha256 == identity["target_config_sha256"]
            and source.policy_registry_sha256 == identity["policy_sha256"]
            and source.user_task_sha256 == fingerprint(runtime.task_contract.user_task)
            and source.target_origin == executor.config.base_url
            and source.environment == executor.config.environment
            and source.selected_policy_ids == [s.policy_id for s in scenario.steps]
            and [s.model_dump() for s in source.plan_structure] == structure
            and len(source.steps) == len(scenario.steps)
            and all(result.step_id == step.id and result.operation_id == step.operation_id
                    and result.policy_template_sha256 == identity["step_policy_sha256"][step.id]
                    and result.outcome == Outcome.PASS and result.attempts and result.checks
                    and all(c.passed for c in result.checks)
                    for result, step in zip(source.steps, scenario.steps))):
        raise ValueError("REGRESSION_SOURCE_NOT_VERIFIED")
    path = validate_destination(output)
    module = "test_agenttest_" + uuid4().hex + ".py"
    files = {"scenario.json": (scenario.model_dump_json(indent=2) + "\n").encode(),
             module: PYTEST_TEMPLATE.encode(), "README.md": README.encode()}
    manifest = RegressionManifest(schema_version="agenttest.regression.v1",
        source_run_id=source.run_id,
        source_report_sha256=fingerprint(source.model_dump(mode="json")),
        source_step_policy_sha256={s.step_id: s.policy_sha256 for s in source.steps},
        **identity, test_module=module,
        files={name: hashlib.sha256(data).hexdigest() for name, data in files.items()})
    with pinned_directory(path.parent, "", create=False) as parent:
        if os.name == "posix":
            os.mkdir(path.name, 0o700, dir_fd=parent.descriptor)
        else:
            path.mkdir()
        with pinned_directory(path.parent, path.name, create=False) as directory:
            for name, data in {**files, "manifest.json": (
                    manifest.model_dump_json(indent=2) + "\n").encode()}.items():
                with os.fdopen(directory.open(name, create=True), "wb") as destination:
                    destination.write(data)
    return manifest


def load_regression(directory: Path) -> tuple[RegressionManifest, Scenario]:
    path = directory.absolute()
    if ".." in directory.parts:
        raise ValueError("REGRESSION_INPUT_INVALID")
    with pinned_directory(path.parent, path.name, create=False) as pinned:
        def read(name: str) -> bytes:
            with os.fdopen(pinned.open(name, readonly=True), "rb") as source:
                raw = source.read(200_001)
            if len(raw) > 200_000:
                raise ValueError("REGRESSION_FILE_TOO_LARGE")
            return raw

        manifest = RegressionManifest.model_validate_json(read("manifest.json"))
        if set(manifest.files) != {"scenario.json", "README.md", manifest.test_module}:
            raise ValueError("REGRESSION_FILE_SET_INVALID")
        files = {name: read(name) for name in manifest.files}
        if any(hashlib.sha256(raw).hexdigest() != manifest.files[name]
               for name, raw in files.items()):
            raise ValueError("REGRESSION_CONTENT_CHANGED")
        if files[manifest.test_module] != PYTEST_TEMPLATE.encode() or files["README.md"] != (
                README.encode()):
            raise ValueError("REGRESSION_TEMPLATE_CHANGED")
        scenario = Scenario.model_validate_json(files["scenario.json"])
    if fingerprint(scenario.model_dump()) != manifest.scenario_sha256:
        raise ValueError("REGRESSION_PLAN_CHANGED")
    return manifest, scenario


async def run_regression(directory: Path, runtime: RegressionRuntime) -> RunReport:
    """A fresh operator-plan execution, never a continuation of the source run."""
    if not isinstance(runtime.transport, httpx.AsyncBaseTransport):
        raise ValueError("REGRESSION_EXPLICIT_TRANSPORT_REQUIRED")
    manifest, scenario = load_regression(directory)
    executor, identity = _validated(runtime, scenario)
    if any(getattr(manifest, key) != value for key, value in identity.items()):
        raise ValueError("REGRESSION_AUTHORITY_CHANGED")
    return await executor.run(scenario)


def assert_regression_passed(report: RunReport) -> None:
    if not (report.outcome == Outcome.PASS and report.completed
            and report.dsl_valid and report.policy_authorized):
        raise AssertionError("REGRESSION_" + report.outcome.value + " run_id=" + report.run_id)
